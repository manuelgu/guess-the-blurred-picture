const DICTS: Record<Lang, Dict> = { en, de, sv };

function detectLang(): Lang {
  const saved = storage.get<Lang>("lang");
  if (saved && Object.hasOwn(DICTS, saved)) return saved;
  const nav = navigator.language.slice(0, 2);
  return nav === "de" || nav === "sv" ? nav : "en";
}

export type T = (key: StringKey, vars?: Record<string, string | number>) => string;

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);
  const setLang = useCallback((l: Lang) => {
    storage.set("lang", l);
    setLangState(l);
    document.documentElement.lang = l;
  }, []);
  const t = useCallback<T>(
    (key, vars) => {
      let s = DICTS[lang][key] ?? en[key];
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("I18nProvider missing");
  return ctx;
}

export function LangPicker({ className = "" }: { className?: string }) {
  const { lang, setLang } = useI18n();
  return (
    <div className={`lang-picker ${className}`}>
      {LANGS.map((l) => (
        <button key={l.id} className={l.id === lang ? "active" : ""} onClick={() => setLang(l.id)} title={l.label}>
          {l.id.toUpperCase()}
        </button>
      ))}
    </div>
  );
}
